// The typed boundary between the web app and the compiled OpenMLS module (`crypto-wasm`).
// The module is injected, so tests use a fake. Nothing here does cryptography: it checks the
// module is the expected build, turns results into plain types, frees WASM objects, and makes
// sure error details never cross into the app (only a short code does).

/** MLS_128_DHKEMX25519_CHACHA20POLY1305_SHA256_Ed25519 (RFC 9420 registry). */
export const EXPECTED_CIPHERSUITE = 3;

export type BridgeErrorCode =
  | 'incompatible_module'
  | 'malformed'
  | 'unsupported_ciphersuite'
  | 'unknown_group'
  | 'rejected'
  | 'too_large'
  | 'internal';

const MODULE_CODES: readonly string[] = [
  'malformed',
  'unsupported_ciphersuite',
  'unknown_group',
  'rejected',
  'too_large',
];

export class BridgeError extends Error {
  constructor(readonly code: BridgeErrorCode) {
    super(code);
    this.name = 'BridgeError';
  }
}

interface Freeable {
  /** Generated by wasm-bindgen on every exported object. */
  free: () => void;
}

/** The shape wasm-bindgen generates for `crypto-wasm/src/wasm.rs`. */
export interface WasmClientLike extends Freeable {
  key_package(): Uint8Array;
  create_group(): Uint8Array;
  add_member(
    group: Uint8Array,
    keyPackage: Uint8Array,
  ): { commit(): Uint8Array; welcome(): Uint8Array } & Freeable;
  join(welcome: Uint8Array): Uint8Array;
  remove_member(group: Uint8Array, index: number): Uint8Array;
  encrypt(group: Uint8Array, plaintext: Uint8Array): Uint8Array;
  receive(
    group: Uint8Array,
    bytes: Uint8Array,
  ): { kind(): number; message(): Uint8Array } & Freeable;
  member_count(group: Uint8Array): number;
  member_index(group: Uint8Array, position: number): number;
  member_identity(group: Uint8Array, index: number): Uint8Array;
}

export interface MlsModule {
  ciphersuite_id(): number;
  WasmClient: new (identity: Uint8Array) => WasmClientLike;
}

export type Received =
  { kind: 'message'; text: Uint8Array } | { kind: 'group-changed' } | { kind: 'removed' };

export interface GroupMember {
  index: number;
  identity: Uint8Array;
}

const KIND_MESSAGE = 0;
const KIND_GROUP_CHANGED = 1;
const KIND_REMOVED = 2;

/** Runs a module call; any failure becomes a `BridgeError` carrying only a known code. */
function call<T>(action: () => T): T {
  try {
    return action();
  } catch (error) {
    const known = MODULE_CODES.includes(error as string);
    throw new BridgeError(known ? (error as BridgeErrorCode) : 'internal');
  }
}

export class Device {
  constructor(private readonly client: WasmClientLike) {}

  keyPackage(): Uint8Array {
    return call(() => this.client.key_package());
  }

  createGroup(): Uint8Array {
    return call(() => this.client.create_group());
  }

  join(welcome: Uint8Array): Uint8Array {
    return call(() => this.client.join(welcome));
  }

  addMember(
    group: Uint8Array,
    keyPackage: Uint8Array,
  ): { commit: Uint8Array; welcome: Uint8Array } {
    return call(() => {
      const added = this.client.add_member(group, keyPackage);
      try {
        return { commit: added.commit(), welcome: added.welcome() };
      } finally {
        added.free();
      }
    });
  }

  removeMember(group: Uint8Array, index: number): Uint8Array {
    return call(() => this.client.remove_member(group, index));
  }

  encrypt(group: Uint8Array, plaintext: Uint8Array): Uint8Array {
    return call(() => this.client.encrypt(group, plaintext));
  }

  receive(group: Uint8Array, bytes: Uint8Array): Received {
    return call(() => {
      const received = this.client.receive(group, bytes);
      try {
        return toReceived(received.kind(), received.message());
      } finally {
        received.free();
      }
    });
  }

  members(group: Uint8Array): GroupMember[] {
    return call(() => {
      const count = this.client.member_count(group);
      return Array.from({ length: count }, (_, position) => {
        const index = this.client.member_index(group, position);
        return { index, identity: this.client.member_identity(group, index) };
      });
    });
  }

  /** Releases the WASM memory. Do not use the device afterwards. */
  close(): void {
    this.client.free();
  }
}

function toReceived(kind: number, message: Uint8Array): Received {
  switch (kind) {
    case KIND_MESSAGE:
      return { kind: 'message', text: message };
    case KIND_GROUP_CHANGED:
      return { kind: 'group-changed' };
    case KIND_REMOVED:
      return { kind: 'removed' };
    default:
      throw new TypeError();
  }
}

export interface MlsBridge {
  newDevice(identity: Uint8Array): Device;
}

/** Refuses to run against a module built for a different ciphersuite. */
export function createBridge(module: MlsModule): MlsBridge {
  if (module.ciphersuite_id() !== EXPECTED_CIPHERSUITE)
    throw new BridgeError('incompatible_module');
  return { newDevice: (identity) => call(() => new Device(new module.WasmClient(identity))) };
}
